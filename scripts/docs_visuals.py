def repo_root_from(path: Path | None = None) -> Path:
    start = (path or Path(__file__)).resolve()
    for candidate in (start, *start.parents):
        if (candidate / "mkdocs.yml").exists() and (candidate / "docs").is_dir():
            return candidate
    raise RuntimeError("Could not locate repository root (mkdocs.yml + docs/)")


def _read_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8")


def _sha_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _safe_id(value: str) -> str:
    value = re.sub(r"[^A-Za-z0-9_]", "_", value)
    return value if value and not value[0].isdigit() else f"n_{value}"


def generate_diagrams(root: Path) -> list[Path]:
    spec_path = root / DIAGRAM_SPEC
    spec = _read_json(spec_path)
    source_hash = _sha_file(spec_path)
    outputs: list[Path] = []
    for diagram in spec.get("diagrams", []):
        diagram_id = str(diagram["id"])
        direction = str(diagram.get("direction", "TD"))
        if direction not in {"TD", "TB", "BT", "LR", "RL"}:
            raise ValueError(f"invalid Mermaid direction for {diagram_id}: {direction}")
        known = {str(node["id"]) for node in diagram.get("nodes", [])}
        lines = [f"flowchart {direction}"]
        for node in diagram.get("nodes", []):
            node_id = str(node["id"])
            label = str(node.get("label", node_id)).replace('"', "\\\"")
            lines.append(f'    {_safe_id(node_id)}["{label}"]')
        for edge in diagram.get("edges", []):
            source, target = str(edge["from"]), str(edge["to"])
            if source not in known or target not in known:
                raise ValueError(f"diagram {diagram_id} references unknown node: {source} -> {target}")
            label = str(edge.get("label", "")).strip().replace('"', "\\\"")
            arrow = f'-->|"{label}"|' if label else "-->"
            lines.append(f"    {_safe_id(source)} {arrow} {_safe_id(target)}")
        title = str(diagram.get("title", diagram_id.replace("-", " ").title()))
        output = root / GENERATED_VISUAL_ROOT / f"{diagram_id}.md"
        _write(
            output,
            f"# {title}\n\n"
            "<!-- Generated by scripts/docs_visuals.py; edit docs/visuals/diagrams.json. -->\n\n"
            f"Source spec SHA-256: `{source_hash}`\n\n"
            "```mermaid\n" + "\n".join(lines) + "\n```\n",
        )
        outputs.append(output)
    return outputs


def _palette() -> list[str]:
    """Color palette for plot series (deterministic, theme-aware)."""
    return ["#2563eb", "#dc2626", "#059669", "#7c3aed", "#d97706", "#0891b2"]


def _line_svg(plot: dict[str, Any], rows: list[dict[str, str]]) -> str:
    width, height = 960, 520
    left, right, top, bottom = 82, 32, 62, 76
    inner_w, inner_h = width - left - right, height - top - bottom
    x_col = str(plot["x"])
    series = list(plot.get("series", []))
    if not rows or not series:
        raise ValueError(f"plot {plot.get('id')} requires rows and series")
    xs = [float(row[x_col]) for row in rows]
    ys = [float(row[str(item["column"])]) for item in series for row in rows]
    xmin, xmax, ymin, ymax = min(xs), max(xs), min(ys), max(ys)
    xmax = xmax if xmax != xmin else xmin + 1.0
    ymax = ymax if ymax != ymin else ymin + 1.0
    pad = max((ymax - ymin) * 0.08, 0.01)
    ymin, ymax = ymin - pad, ymax + pad

    def sx(v: float) -> float:
        return left + (v - xmin) / (xmax - xmin) * inner_w

    def sy(v: float) -> float:
        return top + inner_h - (v - ymin) / (ymax - ymin) * inner_h

    palette = _palette()
    title = html.escape(str(plot.get("title", plot.get("id", "plot"))))
    desc = html.escape(str(plot.get("description", "Generated documentation plot.")))
    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" role="img" aria-labelledby="title desc">',
        f'<title id="title">{title}</title>',
        f'<desc id="desc">{desc}</desc>',
        '<rect width="100%" height="100%" fill="white"/>',
        f'<text x="{width/2}" y="32" text-anchor="middle" font-family="sans-serif" font-size="22">{title}</text>',
        f'<line x1="{left}" y1="{top}" x2="{left}" y2="{top+inner_h}" stroke="#333"/>',
        f'<line x1="{left}" y1="{top+inner_h}" x2="{left+inner_w}" y2="{top+inner_h}" stroke="#333"/>',
    ]
    for tick in range(6):
        frac = tick / 5
        x, y = left + frac * inner_w, top + frac * inner_h
        xv, yv = xmin + frac * (xmax - xmin), ymax - frac * (ymax - ymin)
        parts += [
            f'<text x="{x:.1f}" y="{top+inner_h+24}" text-anchor="middle" font-family="sans-serif" font-size="12">{xv:.3g}</text>',
            f'<text x="{left-10}" y="{y+4:.1f}" text-anchor="end" font-family="sans-serif" font-size="12">{yv:.3g}</text>',
        ]
    for index, item in enumerate(series):
        column, color = str(item["column"]), palette[index % len(palette)]
        points = " ".join(f"{sx(float(row[x_col])):.1f},{sy(float(row[column])):.1f}" for row in rows)
        parts.append(f'<polyline fill="none" stroke="{color}" stroke-width="2.5" points="{points}"/>')
        for row in rows:
            parts.append(f'<circle cx="{sx(float(row[x_col])):.1f}" cy="{sy(float(row[column])):.1f}" r="3" fill="{color}"/>')
        lx = left + 14 + index * 170
        label = html.escape(str(item.get("label", column)))
        parts += [
            f'<line x1="{lx}" y1="{height-24}" x2="{lx+24}" y2="{height-24}" stroke="{color}" stroke-width="3"/>',
            f'<text x="{lx+30}" y="{height-20}" font-family="sans-serif" font-size="12">{label}</text>',
        ]
    parts += [
        f'<text x="{left+inner_w/2}" y="{height-48}" text-anchor="middle" font-family="sans-serif" font-size="14">{html.escape(str(plot.get("x_label", x_col)))}</text>',
        f'<text x="22" y="{top+inner_h/2}" text-anchor="middle" font-family="sans-serif" font-size="14" transform="rotate(-90 22 {top+inner_h/2})">{html.escape(str(plot.get("y_label", "value")))}</text>',
        "</svg>\n",
    ]
    return "\n".join(parts)


def _bar_svg(plot: dict[str, Any], rows: list[dict[str, str]]) -> str:
    """Generate bar chart or grouped bar chart with optional error bars."""
    width, height = 960, 520
    left, right, top, bottom = 82, 32, 62, 76
    inner_w, inner_h = width - left - right, height - top - bottom
    x_col = str(plot["x"])
    series = list(plot.get("series", []))
    if not rows or not series:
        raise ValueError(f"plot {plot.get('id')} requires rows and series")

    # Extract y values and error bars if present
    ys = []
    for item in series:
        col = str(item["column"])
        ys.extend([float(row[col]) for row in rows])
    ymin, ymax = min(ys), max(ys)
    ymax = ymax if ymax != ymin else ymin + 1.0
    pad = max((ymax - ymin) * 0.08, 0.01)
    ymin, ymax = ymin - pad, ymax + pad

    def sy(v: float) -> float:
        return top + inner_h - (v - ymin) / (ymax - ymin) * inner_h

    palette = _palette()
    title = html.escape(str(plot.get("title", plot.get("id", "plot"))))
    desc = html.escape(str(plot.get("description", "Generated documentation plot.")))
    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" role="img" aria-labelledby="title desc">',
        f'<title id="title">{title}</title>',
        f'<desc id="desc">{desc}</desc>',
        '<rect width="100%" height="100%" fill="white"/>',
        f'<text x="{width/2}" y="32" text-anchor="middle" font-family="sans-serif" font-size="22">{title}</text>',
        f'<line x1="{left}" y1="{top}" x2="{left}" y2="{top+inner_h}" stroke="#333"/>',
        f'<line x1="{left}" y1="{top+inner_h}" x2="{left+inner_w}" y2="{top+inner_h}" stroke="#333"/>',
    ]

    # Y-axis ticks
    for tick in range(6):
        frac = tick / 5
        y = top + frac * inner_h
        yv = ymax - frac * (ymax - ymin)
        parts += [
            f'<line x1="{left-5}" y1="{y:.1f}" x2="{left}" y2="{y:.1f}" stroke="#333"/>',
            f'<text x="{left-10}" y="{y+4:.1f}" text-anchor="end" font-family="sans-serif" font-size="12">{yv:.3g}</text>',
        ]

    # Draw bars
    n_series = len(series)
    bar_width = (inner_w / len(rows)) / (n_series + 0.5) if rows else 0
    for row_idx, row in enumerate(rows):
        x_label = html.escape(str(row[x_col]))
        x_pos = left + (row_idx + 0.5) * inner_w / len(rows)

        for series_idx, item in enumerate(series):
            col = str(item["column"])
            val = float(row[col])
            error_col = item.get("error_column")
            error = float(row[error_col]) if error_col and error_col in row else 0.0

            bar_x = x_pos + (series_idx - n_series / 2 + 0.5) * bar_width
            bar_h = (val - ymin) / (ymax - ymin) * inner_h if ymax != ymin else 0
            color = palette[series_idx % len(palette)]

            # Draw error bar if present
            if error > 0:
                err_top = sy(val + error)
                err_bot = sy(val - error)
                parts.append(f'<line x1="{bar_x+bar_width/2:.1f}" y1="{err_top:.1f}" x2="{bar_x+bar_width/2:.1f}" y2="{err_bot:.1f}" stroke="{color}" stroke-width="1"/>')

            # Draw bar
            bar_y = sy(val)
            parts.append(f'<rect x="{bar_x:.1f}" y="{bar_y:.1f}" width="{bar_width:.1f}" height="{bar_h:.1f}" fill="{color}" stroke="#333" stroke-width="0.5"/>')

        # X-axis label
        parts.append(f'<text x="{x_pos:.1f}" y="{top+inner_h+20}" text-anchor="middle" font-family="sans-serif" font-size="11">{x_label}</text>')

    # Legend
    for index, item in enumerate(series):
        lx = left + 14 + index * 170
        color = palette[index % len(palette)]
        label = html.escape(str(item.get("label", item["column"])))
        parts += [
            f'<rect x="{lx}" y="{height-28}" width="16" height="16" fill="{color}" stroke="#333" stroke-width="0.5"/>',
            f'<text x="{lx+22}" y="{height-15}" font-family="sans-serif" font-size="12">{label}</text>',
        ]

    parts += [
        f'<text x="{left+inner_w/2}" y="{height-48}" text-anchor="middle" font-family="sans-serif" font-size="14">{html.escape(str(plot.get("x_label", x_col)))}</text>',
        f'<text x="22" y="{top+inner_h/2}" text-anchor="middle" font-family="sans-serif" font-size="14" transform="rotate(-90 22 {top+inner_h/2})">{html.escape(str(plot.get("y_label", "value")))}</text>',
        "</svg>\n",
    ]
    return "\n".join(parts)


def _scatter_svg(plot: dict[str, Any], rows: list[dict[str, str]]) -> str:
    """Generate scatter plot, optionally with Pareto frontier."""
    width, height = 960, 520
    left, right, top, bottom = 82, 32, 62, 76
    inner_w, inner_h = width - left - right, height - top - bottom
    x_col = str(plot["x"])
    y_col = str(plot["y"])
    if not rows:
        raise ValueError(f"plot {plot.get('id')} requires rows")

    xs = [float(row[x_col]) for row in rows]
    ys = [float(row[y_col]) for row in rows]
    xmin, xmax, ymin, ymax = min(xs), max(xs), min(ys), max(ys)
    xmax = xmax if xmax != xmin else xmin + 1.0
    ymax = ymax if ymax != ymin else ymin + 1.0
    xpad = max((xmax - xmin) * 0.08, 0.01)
    ypad = max((ymax - ymin) * 0.08, 0.01)
    xmin, xmax, ymin, ymax = xmin - xpad, xmax + xpad, ymin - ypad, ymax + ypad

    def sx(v: float) -> float:
        return left + (v - xmin) / (xmax - xmin) * inner_w

    def sy(v: float) -> float:
        return top + inner_h - (v - ymin) / (ymax - ymin) * inner_h

    palette = _palette()
    title = html.escape(str(plot.get("title", plot.get("id", "plot"))))
    desc = html.escape(str(plot.get("description", "Generated documentation plot.")))
    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" role="img" aria-labelledby="title desc">',
        f'<title id="title">{title}</title>',
        f'<desc id="desc">{desc}</desc>',
        '<rect width="100%" height="100%" fill="white"/>',
        f'<text x="{width/2}" y="32" text-anchor="middle" font-family="sans-serif" font-size="22">{title}</text>',
        f'<line x1="{left}" y1="{top}" x2="{left}" y2="{top+inner_h}" stroke="#333"/>',
        f'<line x1="{left}" y1="{top+inner_h}" x2="{left+inner_w}" y2="{top+inner_h}" stroke="#333"/>',
    ]

    # Axes
    for tick in range(6):
        frac = tick / 5
        x, y = left + frac * inner_w, top + frac * inner_h
        xv, yv = xmin + frac * (xmax - xmin), ymax - frac * (ymax - ymin)
        parts += [
            f'<text x="{x:.1f}" y="{top+inner_h+24}" text-anchor="middle" font-family="sans-serif" font-size="12">{xv:.3g}</text>',
            f'<text x="{left-10}" y="{y+4:.1f}" text-anchor="end" font-family="sans-serif" font-size="12">{yv:.3g}</text>',
        ]

    # Draw scatter points
    color_col = plot.get("color_column")
    for idx, row in enumerate(rows):
        x, y = float(row[x_col]), float(row[y_col])
        color = palette[idx % len(palette)] if not color_col else palette[int(float(row[color_col])) % len(palette)]
        parts.append(f'<circle cx="{sx(x):.1f}" cy="{sy(y):.1f}" r="4" fill="{color}" stroke="#333" stroke-width="0.5" opacity="0.8"/>')

    # Pareto frontier if requested
    if plot.get("pareto"):
        frontier = _compute_pareto_frontier([(float(row[x_col]), float(row[y_col])) for row in rows])
        if frontier:
            frontier_sorted = sorted(frontier)
            points = " ".join(f"{sx(x):.1f},{sy(y):.1f}" for x, y in frontier_sorted)
            parts.append(f'<polyline fill="none" stroke="#666" stroke-width="1.5" stroke-dasharray="5,5" points="{points}"/>')

    parts += [
        f'<text x="{left+inner_w/2}" y="{height-48}" text-anchor="middle" font-family="sans-serif" font-size="14">{html.escape(str(plot.get("x_label", x_col)))}</text>',
        f'<text x="22" y="{top+inner_h/2}" text-anchor="middle" font-family="sans-serif" font-size="14" transform="rotate(-90 22 {top+inner_h/2})">{html.escape(str(plot.get("y_label", y_col)))}</text>',
        "</svg>\n",
    ]
    return "\n".join(parts)


def _compute_pareto_frontier(points: list[tuple[float, float]]) -> list[tuple[float, float]]:
    """Compute Pareto frontier: retain points that are not dominated.

    A point (x1, y1) dominates (x2, y2) if x1 <= x2 AND y1 >= y2 with at least one strict.
    For efficiency on plot-sized data, sort by x and keep max y seen so far.
    """
    if not points:
        return []
    sorted_points = sorted(points)
    frontier = []
    max_y = float("-inf")
    for x, y in sorted_points:
        if y > max_y:
            frontier.append((x, y))
            max_y = y
    return frontier


def generate_plots(root: Path) -> list[Path]:
    spec_path = root / PLOT_SPEC
    spec = _read_json(spec_path)
    outputs: list[Path] = []
    for plot in spec.get("plots", []):
        plot_id = str(plot["id"])
        kind = plot.get("kind", "line")
        if kind not in {"line", "bar", "scatter"}:
            raise ValueError(f"unsupported plot kind for {plot_id}: {kind}")
        source = root / str(plot["source"])
        with source.open("r", encoding="utf-8", newline="") as stream:
            rows = list(csv.DictReader(stream))

        # Dispatch to appropriate SVG generator
        if kind == "line":
            svg = _line_svg(plot, rows)
        elif kind == "bar":
            svg = _bar_svg(plot, rows)
        elif kind == "scatter":
            svg = _scatter_svg(plot, rows)
        else:
            raise ValueError(f"unhandled plot kind: {kind}")

        svg_path = root / GENERATED_VISUAL_ROOT / f"{plot_id}.svg"
        _write(svg_path, svg)
        provenance = {
            "schema_version": 1,
            "plot_id": plot_id,
            "plot_kind": kind,
            "evidence_class": plot.get("evidence_class", "unspecified"),
            "generator": "scripts/docs_visuals.py",
            "spec": PLOT_SPEC.as_posix(),
            "spec_sha256": _sha_file(spec_path),
            "source": str(plot["source"]),
            "source_sha256": _sha_file(source),
            "output_sha256": hashlib.sha256(svg.encode()).hexdigest(),
        }
        provenance_path = root / GENERATED_VISUAL_ROOT / f"{plot_id}.provenance.json"
        _write(provenance_path, json.dumps(provenance, indent=2, sort_keys=True) + "\n")
        title = str(plot.get("title", plot_id.replace("-", " ").title()))
        page_path = root / GENERATED_VISUAL_ROOT / f"{plot_id}.md"
        _write(
            page_path,
            f"# {title}\n\n"
            "<!-- Generated by scripts/docs_visuals.py; edit docs/visuals/plots.json or its source data. -->\n\n"
            f"{plot.get('description', 'Generated documentation plot.')}\n\n"
            f"![{title}]({plot_id}.svg)\n\n"
            f"Evidence class: `{plot.get('evidence_class', 'unspecified')}`. Source: `{plot['source']}`. Plot kind: `{kind}`.\n",
        )
        outputs += [svg_path, provenance_path, page_path]
    return outputs


def generate_all(root: Path | None = None) -> list[Path]:
    repo = (root or repo_root_from()).resolve()
    diagrams = generate_diagrams(repo)
    plots = generate_plots(repo)
    pages = diagrams + [path for path in plots if path.suffix == ".md"]
    nav = root_nav = repo / GENERATED_VISUAL_ROOT / ".pages"
    _write(nav, "title: Generated Visuals\nnav:\n" + "".join(f"  - {path.name}\n" for path in pages) + "  - ...\n")
    return diagrams + plots + [root_nav]


def visual_status(relative_path: Path, text: str) -> str:
    if VISUAL_RE.search(text):
        return "visualized"
    if VISUAL_EXEMPT_RE.search(text):
        return "exempt"
    return "legacy_missing" if f"docs/{relative_path.as_posix()}".startswith(VISUAL_CRITICAL_PREFIXES) else "n/a"


def _changed_visual_docs(root: Path) -> list[Path]:
    base = os.environ.get("DOCS_VISUAL_BASE") or os.environ.get("GITHUB_BASE_REF")
    if not base:
        return []
    output: str | None = None
    failures: list[str] = []
    for candidate in (f"origin/{base}", base):
        try:
            result = subprocess.run(
                ["git", "-C", str(root), "diff", "--name-status", f"{candidate}...HEAD", "--", "docs/architecture", "docs/experiments"],
                check=True,
                text=True,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
            )
            output = result.stdout
            break
        except OSError as exc:
            failures.append(f"{candidate}: {exc}")
        except subprocess.CalledProcessError as exc:
            # Keep git's own stderr. Swallowing it (the original behaviour)
            # made an ENVIRONMENT problem -- "detected dubious ownership in
            # repository", which is what broke this check in CI on every PR --
            # indistinguishable from a genuinely unresolvable ref.
            detail = (exc.stderr or "").strip().replace("\n", " ")
            failures.append(f"{candidate}: exit {exc.returncode}{': ' + detail if detail else ''}")
    if output is None:
        raise RuntimeError(
            f"could not resolve docs visual comparison base {base!r}; refusing to skip "
            f"changed-doc coverage (tried: {'; '.join(failures)})"
        )
    paths: list[Path] = []
    for line in output.splitlines():
        fields = line.split("\t")
        if fields and not fields[0].startswith("D") and fields[-1].endswith(".md"):
            paths.append(Path(fields[-1]))
    return paths


class _SafeRedirectHandler(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):  # noqa: ANN001
        redirected = super().redirect_request(req, fp, code, msg, headers, newurl)
        if redirected and (urlparse(newurl).hostname or "").lower() not in GITHUB_AUTH_HOSTS:
            redirected.remove_header("Authorization")
        return redirected


def _download(url: str) -> bytes:
    headers = {"User-Agent": "eligsir-docs-visual-sync", "Accept": "application/octet-stream"}
    token = os.environ.get("GITHUB_TOKEN")
    if token and (urlparse(url).hostname or "").lower() in GITHUB_AUTH_HOSTS:
        headers["Authorization"] = f"Bearer {token}"
    request = urllib.request.Request(url, headers=headers)
    with urllib.request.build_opener(_SafeRedirectHandler()).open(request, timeout=60) as response:
        return response.read()


def _asset_errors(root: Path, asset: dict[str, Any]) -> list[str]:
    required = {"id", "kind", "destination", "source", "caption", "alt"}
    missing = sorted(required - asset.keys())
    if missing:
        return [f"asset missing fields {missing}: {asset}"]
    errors: list[str] = []
    source = asset.get("source")
    if not isinstance(source, dict) or source.get("type") not in {"repo", "experiment_host", "release", "artifact"} or not source.get("locator"):
        errors.append(f"asset {asset.get('id')} has invalid source contract")
    destination = (root / str(asset["destination"])).resolve()
    if (root / "docs/assets").resolve() not in destination.parents:
        errors.append(f"asset {asset.get('id')} destination must live under docs/assets/")
    sha = str(asset.get("sha256", ""))
    if sha and not re.fullmatch(r"[0-9a-fA-F]{64}", sha):
        errors.append(f"asset {asset.get('id')} has invalid sha256")
    return errors


def sync_assets(root: Path, asset_id: str | None = None, source_type: str | None = None) -> list[str]:
    actions: list[str] = []
    for asset in _read_json(root / ASSET_MANIFEST).get("assets", []):
        source = asset["source"]
        if asset_id and asset.get("id") != asset_id or source_type and source.get("type") != source_type:
            continue
        source_kind, locator = str(source["type"]), str(source["locator"])
        if source_kind == "repo":
            data = (root / locator).read_bytes()
        elif source_kind == "experiment_host":
            data = Path(locator).expanduser().read_bytes()
        else:
            data = _download(locator)
        digest = hashlib.sha256(data).hexdigest()
        expected = str(asset.get("sha256", ""))
        if expected and digest.lower() != expected.lower():
            raise ValueError(f"asset {asset['id']} SHA-256 mismatch: expected {expected}, got {digest}")
        destination = root / str(asset["destination"])
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(data)
        actions.append(f"{asset['id']} -> {asset['destination']} ({digest})")
    return actions


def audit(root: Path | None = None) -> tuple[list[str], list[str]]:
    repo = (root or repo_root_from()).resolve()
    errors: list[str] = []
    warnings: list[str] = []
    try:
        generate_all(repo)
    except (OSError, ValueError, KeyError, json.JSONDecodeError) as exc:
        return [f"visual generation failed: {exc}"], warnings
    try:
        changed_docs = _changed_visual_docs(repo)
    except RuntimeError as exc:
        errors.append(str(exc))
        changed_docs = []
    for rel in changed_docs:
        path = repo / rel
        if path.exists() and visual_status(rel.relative_to("docs"), path.read_text(encoding="utf-8", errors="replace")) not in {"visualized", "exempt"}:
            errors.append(f"{rel} is a changed visual-critical doc without a Mermaid/image visual or visual_exempt frontmatter")
    seen: set[str] = set()
    for asset in _read_json(repo / ASSET_MANIFEST).get("assets", []):
        errors += _asset_errors(repo, asset)
        asset_id = str(asset.get("id", ""))
        if asset_id in seen:
            errors.append(f"duplicate visual asset id: {asset_id}")
        seen.add(asset_id)
        destination = repo / str(asset.get("destination", ""))
        source_kind = str(asset.get("source", {}).get("type", ""))
        required = bool(asset.get("required_in_ci", source_kind == "repo"))
        if not destination.exists():
            message = f"visual asset {asset_id} not materialized at {asset.get('destination')} (source={source_kind})"
            (errors if required else warnings).append(message)
        elif asset.get("sha256") and _sha_file(destination).lower() != str(asset["sha256"]).lower():
            errors.append(f"visual asset {asset_id} destination hash mismatch")
    return errors, warnings


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate and validate EliGSiR documentation visuals")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("generate")
    sub.add_parser("check")
    sync = sub.add_parser("sync-assets")
    sync.add_argument("--asset-id")
    sync.add_argument("--source-type", choices=["repo", "experiment_host", "release", "artifact"])
    args = parser.parse_args(argv)
    root = repo_root_from()
    if args.command == "generate":
        for path in generate_all(root):
            print(path.relative_to(root))
        return 0
    if args.command == "sync-assets":
        for action in sync_assets(root, args.asset_id, args.source_type):
            print(action)
        return 0
    errors, warnings = audit(root)
    for warning in warnings:
        print(f"WARNING: {warning}", file=sys.stderr)
    if errors:
        print("Documentation visual integrity check failed:", file=sys.stderr)
        for error in errors:
            print(f"- {error}", file=sys.stderr)
        return 1
    print("Documentation visual integrity check passed.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
