@dataclass(frozen=True)
class ApiModule:
    module: str
    source: Path
    output: Path


def repo_root_from(path: Path | None = None) -> Path:
    start = (path or Path(__file__)).resolve()
    for candidate in (start, *start.parents):
        if (candidate / "mkdocs.yml").exists() and (candidate / "docs").is_dir():
            return candidate
    raise RuntimeError("Could not locate repository root (mkdocs.yml + docs/)")


def discover_public_modules(root: Path) -> list[ApiModule]:
    package_root = root / "eligsir"
    modules: list[ApiModule] = []
    if not package_root.is_dir():
        return modules

    for source in sorted(package_root.rglob("*.py")):
        rel = source.relative_to(root)
        parts = rel.with_suffix("").parts
        if any(part in API_EXCLUDED_PARTS for part in parts):
            continue
        if source.name == "__main__.py":
            continue
        if source.name.startswith("_") and source.name != "__init__.py":
            continue

        if source.name == "__init__.py":
            module_parts = parts[:-1]
            if not module_parts:
                continue
            output = GENERATED_API_ROOT.joinpath(*module_parts, "index.md")
        else:
            module_parts = parts
            output = GENERATED_API_ROOT.joinpath(*module_parts).with_suffix(".md")

        modules.append(ApiModule(".".join(module_parts), rel, output))
    return modules


def _write_if_changed(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return
    path.write_text(text, encoding="utf-8")


def generate_api_reference(root: Path) -> list[ApiModule]:
    modules = discover_public_modules(root)
    api_root = root / GENERATED_API_ROOT
    expected: set[Path] = set()

    landing = """# Canonical API Reference

This tree is generated automatically from the public Python modules under `eligsir/`.
Do not add module pages by hand. Add or document the canonical Python module instead.

Compatibility and legacy reference pages remain one level above this tree so existing documentation URLs keep resolving.
"""
    landing_path = api_root / "index.md"
    _write_if_changed(landing_path, landing)
    expected.add(landing_path.resolve())

    pages = """title: Canonical API
nav:
  - index.md
  - eligsir
  - ...
"""
    pages_path = api_root / ".pages"
    _write_if_changed(pages_path, pages)
    expected.add(pages_path.resolve())

    for item in modules:
        output = root / item.output
        text = (
            f"# `{item.module}`\n\n"
            "<!-- Generated by scripts/docs_catalog.py; edit the Python source, not this page. -->\n\n"
            f"::: {item.module}\n"
        )
        _write_if_changed(output, text)
        expected.add(output.resolve())

    if api_root.exists():
        for existing in sorted(api_root.rglob("*"), reverse=True):
            if existing.is_file() and existing.resolve() not in expected:
                existing.unlink()
        for directory in sorted((p for p in api_root.rglob("*") if p.is_dir()), reverse=True):
            try:
                directory.rmdir()
            except OSError:
                pass
    return modules


def _git(root: Path, *args: str) -> str | None:
    try:
        proc = subprocess.run(
            ["git", "-C", str(root), *args],
            check=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            text=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return None
    return proc.stdout.strip() or None


def _head_time(root: Path) -> datetime:
    value = _git(root, "show", "-s", "--format=%cI", "HEAD")
    if value:
        try:
            return datetime.fromisoformat(value.replace("Z", "+00:00"))
        except ValueError:
            pass
    return datetime.now(timezone.utc)


def _last_change(root: Path, relative_path: Path) -> tuple[str, datetime | None]:
    value = _git(root, "log", "-1", "--format=%h%x09%cI", "--", relative_path.as_posix())
    if not value or "\t" not in value:
        return "unknown", None
    commit, stamp = value.split("\t", 1)
    try:
        changed = datetime.fromisoformat(stamp.replace("Z", "+00:00"))
    except ValueError:
        changed = None
    return commit, changed


def _frontmatter_status(text: str) -> str | None:
    if not text.startswith("---\n"):
        return None
    end = text.find("\n---\n", 4)
    if end == -1:
        return None
    match = re.search(r"(?mi)^doc_status\s*:\s*['\"]?([a-z_-]+)", text[4:end])
    return match.group(1).lower() if match else None


def infer_status(relative_path: Path, text: str) -> str:
    """Classify every documentation source by its role, conservatively.

    Explicit frontmatter always wins. The filename/folder rules below exist so the
    hundreds of immutable dated EliGSiR investigation records do not appear as
    unclassified current guidance merely because adding frontmatter to every
    historical evidence file would churn durable evidence paths.
    """

    declared = _frontmatter_status(text)
    if declared:
        return declared

    rel = relative_path.as_posix()
    name = relative_path.name.lower()
    stem = relative_path.stem.lower()
    sample = "\n".join(text.splitlines()[:60]).lower()

    if re.search(r"(?m)^(?:>|#{1,4}\s*)?(?:status\s*[:—-].*)?superseded\b", sample) or "superseded by" in sample:
        return "superseded"
    if re.search(r"(?m)^(?:>|#{1,4}\s*)?(?:status\s*[:—-].*)?historical\b", sample):
        return "historical"

    if rel in CURRENT_DOCS:
        return "current"
    if rel in REFERENCE_DOCS or relative_path.parts[:1] == ("reference",):
        return "reference"
    if rel in EVIDENCE_DOCS:
        return "evidence"

    first_section = relative_path.parts[0] if relative_path.parts else ""
    if first_section in EVIDENCE_SECTIONS or re.search(r"(?m)^(?:>|#{1,4}\s*)?.*evidence record\b", sample):
        return "evidence"

    # Dated records are immutable chronology by default. Readout/audit/measurement
    # names are evidence; designs/plans and other dated notes are historical unless
    # their frontmatter explicitly promotes them to current/reference.
    if DATED_NAME.match(name):
        if EVIDENCE_NAME.search(stem):
            return "evidence"
        return "historical"

    if first_section == "architecture":
        if EVIDENCE_NAME.search(stem):
            return "evidence"
        if PLAN_NAME.search(stem):
            return "historical"

    if relative_path.name == "ROADMAP.md":
        return "historical"
    if name.startswith("plan_") or name.endswith("_plan.md") or name.endswith("-plan.md"):
        return "historical"

    return "unclassified"


def _title(relative_path: Path, text: str) -> str:
    match = re.search(r"(?m)^#\s+(.+?)\s*$", text)
    if match:
        return re.sub(r"[`*_]", "", match.group(1)).strip()
    return relative_path.stem.replace("-", " ").replace("_", " ").title()


def _issues(text: str) -> list[str]:
    seen: list[str] = []
    for match in re.finditer(r"(?<![\w/])#(\d{1,5})\b", "\n".join(text.splitlines()[:120])):
        number = match.group(1)
        if number not in seen:
            seen.append(number)
        if len(seen) >= 4:
            break
    return seen


def _escape(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ")


def discover_source_docs(root: Path) -> list[Path]:
    docs = root / "docs"
    results: list[Path] = []
    generated_api = (root / GENERATED_API_ROOT).resolve()
    generated_visuals = (root / GENERATED_VISUAL_ROOT).resolve()
    generated_index = (root / GENERATED_INDEX).resolve()
    for path in sorted(docs.rglob("*")):
        if not path.is_file() or path.suffix.lower() not in {".md", ".ipynb"}:
            continue
        resolved = path.resolve()
        if resolved == generated_index or generated_api in resolved.parents or generated_visuals in resolved.parents:
            continue
        results.append(path.relative_to(docs))
    return results


def generate_documentation_index(root: Path) -> Path:
    docs_root = root / "docs"
    head_time = _head_time(root)
    head_sha = _git(root, "rev-parse", "--short=12", "HEAD") or "unknown"
    rows: list[str] = []

    for rel in discover_source_docs(root):
        path = docs_root / rel
        if path.suffix.lower() == ".md":
            text = path.read_text(encoding="utf-8", errors="replace")
        else:
            text = ""
        title = _title(rel, text)
        status = infer_status(rel, text)
        visuals = visual_status(rel, text)
        commit, changed = _last_change(root, Path("docs") / rel)
        if changed:
            age_days = max(0, (head_time - changed).days)
            changed_text = changed.date().isoformat()
        else:
            age_days = -1
            changed_text = "unknown"

        if status in {"historical", "superseded", "evidence"}:
            signal = "preserve"
        elif age_days >= REVIEW_DUE_DAYS and status in {"current", "unclassified"}:
            signal = "REVIEW_DUE"
        else:
            signal = "ok"

        issue_links = ", ".join(
            f"[#{number}](https://github.com/eligsir-project/eligsir/issues/{number})"
            for number in _issues(text)
        ) or "—"
        source_link = f"[{rel.as_posix()}]({rel.as_posix()})"
        section = rel.parts[0] if len(rel.parts) > 1 else "root"
        last_change = f"{changed_text} `{commit}`" if commit != "unknown" else changed_text
        rows.append(
            "| " + " | ".join(
                _escape(value)
                for value in (source_link, title, section, status, visuals, signal, last_change, issue_links)
            ) + " |"
        )

    body = f"""# Documentation Index

> **Generated automatically** by `scripts/docs_catalog.py` from the documentation source tree at build commit `{head_sha}`. Do not maintain this table by hand.

This is the discovery surface for maintainers and code agents. Existing source paths are intentionally stable because issues, PRs, experiment reports, and historical evidence link to them directly. New documentation should be placed in the most specific existing `docs/` section; folder-driven navigation will publish it automatically.

`REVIEW_DUE` is a **review candidate, not a deletion instruction**. Historical, superseded, and evidence documents are retained intentionally. A document may declare `doc_status` in YAML frontmatter when automatic classification is insufficient.

Visual status is also indexed: `visualized` means the source page contains a Mermaid/image visual, `exempt` is an explicit text-only exception, `legacy_missing` marks architecture/experiment visual debt, and `n/a` means the prospective visual rule does not apply to that section.

Statuses: `current`, `historical`, `superseded`, `evidence`, `reference`, `unclassified`. Review threshold for active/unclassified documents: {REVIEW_DUE_DAYS} days since their last Git change.

**Indexed source documents:** {len(rows)}

| Source | Title | Section | Status | Visuals | Review | Last change | Related issues |
|---|---|---|---|---|---|---|---|
""" + "\n".join(rows) + "\n"
    output = root / GENERATED_INDEX
    _write_if_changed(output, body)
    return output


def generate_all(root: Path | None = None) -> None:
    repo = (root or repo_root_from()).resolve()
    generate_visuals(repo)
    generate_api_reference(repo)
    generate_documentation_index(repo)


if __name__ == "__main__":
    generate_all()
