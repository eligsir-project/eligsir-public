"""Inference of report provenance: native training loop vs. post-hoc regeneration.

This module detects whether a report.json was produced by the live training loop
or regenerated post-hoc from a frozen checkpoint. It is used to populate the
`report_provenance` block in `report.json` so consumers can distinguish:

- `kind: "training_loop"` — report written during live training
- `kind: "regenerated_checkpoint"` — report regenerated post-hoc via render_report.py
- `kind: "unknown"` — insufficient evidence to determine (fail-closed)

Related to issue #630: a regenerated report must be distinguishable from a native
one to every consumer. The provenance block records the evidence that drove the
classification, not just the verdict.

This module is deliberately torch-free (leaf dependency) so torch-free test suites
can import and test it.
"""

from __future__ import annotations

from typing import Optional


def infer_report_provenance(
    *,
    log_prefix: Optional[str] = None,
    train_cams: Optional[list] = None,
    test_cams: Optional[list] = None,
    streaming_scene: Optional[object] = None,
    tb_writer: Optional[object] = None,
    gaussians: Optional[object] = None,
) -> dict:
    """Infer whether this report was generated by the training loop or post-hoc.

    Arguments (all optional, keyword-only):
        log_prefix: The log_prefix passed to write_post_training_report.
        train_cams: The train_cams list passed to write_post_training_report.
        test_cams: The test_cams list passed to write_post_training_report.
        streaming_scene: The streaming_scene object passed to write_post_training_report.
        tb_writer: The tb_writer passed to write_post_training_report.
        gaussians: The gaussians model object passed to write_post_training_report.

    Returns a dict with keys:
        kind: "training_loop" | "regenerated_checkpoint" | "unknown"
        evidence: list of strings explaining the classification
        reasons: dict with individual signal names and their values (for debugging)

    Strategy (fail-closed, regenerated-first):
    1. Check positive markers for regeneration (render_report.py specific)
    2. Check positive markers for native training loop
    3. Default to unknown when ambiguous
    """
    evidence = []
    reasons = {}

    # Normalize inputs
    if train_cams is None:
        train_cams = []
    if test_cams is None:
        test_cams = []

    # --- Regeneration markers (render_report.py) ---

    # Primary signal: log_prefix uniquely set by render_report.py
    if log_prefix == "render_report":
        evidence.append("log_prefix == 'render_report' (unique to render_report.py)")
        reasons["log_prefix_is_render_report"] = True
        return {
            "kind": "regenerated_checkpoint",
            "evidence": evidence,
            "reasons": reasons,
        }

    # Secondary signal: empty train_cams + non-empty test_cams is render_report.py's pattern
    train_cams_empty = len(train_cams) == 0
    test_cams_present = len(test_cams) > 0
    reasons["train_cams_empty"] = train_cams_empty
    reasons["test_cams_present"] = test_cams_present

    if train_cams_empty and test_cams_present:
        evidence.append(
            "train_cams is empty while test_cams is non-empty "
            "(render_report.py passes train_cams=[])"
        )
        # Corroborate with other signals to avoid false positives
        # (theoretically a native run could have only test cameras)

        # Check for optimizer absence (PLY-loaded models don't call training_setup)
        has_optimizer = False
        if gaussians is not None:
            has_optimizer = getattr(gaussians, "optimizer", None) is not None
        reasons["gaussians_has_optimizer"] = has_optimizer

        if not has_optimizer:
            evidence.append("gaussians.optimizer is None (PLY-loaded, no training_setup)")
            return {
                "kind": "regenerated_checkpoint",
                "evidence": evidence,
                "reasons": reasons,
            }

    # --- Native training loop markers ---

    # Strong native signal: streaming_scene is not None
    # (set during live training, not during post-hoc render_report.py)
    if streaming_scene is not None:
        evidence.append("streaming_scene is not None (live training state exists)")
        reasons["streaming_scene_present"] = True
        return {
            "kind": "training_loop",
            "evidence": evidence,
            "reasons": reasons,
        }

    # Native signal: tb_writer is present
    # (training loop supplies writer, post-hoc render_report.py passes None)
    if tb_writer is not None:
        evidence.append("tb_writer is not None (TensorBoard writer exists)")
        reasons["tb_writer_present"] = True
        return {
            "kind": "training_loop",
            "evidence": evidence,
            "reasons": reasons,
        }

    # Native signal: train_cams is non-empty
    # (both training paths supply this, but render_report.py deliberately passes [])
    if train_cams_empty is False:
        evidence.append("train_cams is non-empty (training cameras supplied)")
        # This alone is weak, but corroborate with other checks
        if gaussians is not None:
            has_optimizer = getattr(gaussians, "optimizer", None) is not None
            if has_optimizer:
                evidence.append("gaussians.optimizer is not None (trained model)")
                reasons["gaussians_has_optimizer"] = True
                return {
                    "kind": "training_loop",
                    "evidence": evidence,
                    "reasons": reasons,
                }

    # Check for lineage buffers (present on trained models, absent on PLY-loaded)
    # Note: This is weak evidence since old checkpoints pre-#373 also lack these
    if gaussians is not None:
        has_lineage = hasattr(gaussians, "_lineage_preserving_setup_events")
        has_seed_uid_range = hasattr(gaussians, "seed_uid_range")
        reasons["gaussians_has_lineage"] = has_lineage
        reasons["gaussians_has_seed_uid_range"] = has_seed_uid_range

        if has_lineage or has_seed_uid_range:
            evidence.append(
                "gaussians has lineage buffers "
                "(_lineage_preserving_setup_events or seed_uid_range, streaming-only)"
            )
            return {
                "kind": "training_loop",
                "evidence": evidence,
                "reasons": reasons,
            }

    # --- Cannot determine ---

    reasons["log_prefix"] = log_prefix
    reasons["streaming_scene_present"] = streaming_scene is not None
    reasons["tb_writer_present"] = tb_writer is not None

    return {
        "kind": "unknown",
        "evidence": evidence,
        "reasons": reasons,
    }
